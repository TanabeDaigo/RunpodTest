#!/bin/sh

# ====================================================
# ログ監視スクリプト
# ====================================================
# 概要：
# アプリケーションのログファイルをリアルタイムで監視するスクリプト
# tail -fコマンドを使用してログの更新をリアルタイムで表示します
#
# 機能：
# 1. 指定されたログファイルの監視開始
# 2. リアルタイムでのログ更新の表示
# 3. 環境情報の表示
#
# 使用方法：
# ./tail.sh
#
# 依存ファイル：
# - define.sh: 環境変数定義ファイル
#
# 環境変数：
# - ENV_NAME: 環境名
# - LOG_FILE: 監視対象のログファイルパス
#
# 注意事項：
# - ログファイルが存在することを確認してください
# - ログファイルへの読み取り権限が必要です
# - スクリプトを終了するにはCtrl+Cを押してください
# - ログファイルが大きい場合、表示に時間がかかる場合があります
# ====================================================

source ~/.bashrc
source ~/.bash_profile
source define.sh

SELF=${0}

execute (){

  echo "-------------------------------------------------"
  echo ${ENV_NAME}"環境をログをTailします。"$LOG_FILE

  tail -f $LOG_FILE
  echo "-------------------------------------------------"
}

echo ${ENV_NAME}"環境:"$LOG_FILE

execute;






